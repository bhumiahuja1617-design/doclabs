#!/usr/bin/env python3
"""Run the two bundled target examples and write a measured benchmark report."""
from __future__ import annotations
import argparse
import csv
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / "scripts" / "cli_dock.py"
TARGETS = {
    "1hsg": {"pdb": ROOT / "examples" / "1hsg" / "1hsg.pdb", "ligand": "MK1"},
    "egfr": {"pdb": ROOT / "examples" / "egfr" / "1m17.pdb", "ligand": "AQ4"},
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exhaustiveness", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--target", choices=["all", *TARGETS], default="all")
    parser.add_argument("--reliability", action="store_true")
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument("--topk", type=int, default=5)
    args = parser.parse_args()
    outroot = ROOT / "benchmark" / "results"
    outroot.mkdir(parents=True, exist_ok=True)
    selected = TARGETS.items() if args.target == "all" else [(args.target, TARGETS[args.target])]
    runs = []
    for name, config in selected:
        example = ROOT / "examples" / name
        combined = outroot / f"{name}_ligands.csv"
        records = []
        for filename in ("actives.csv", "decoys.csv"):
            with (example / filename).open(encoding="utf-8", newline="") as stream:
                records.extend(csv.DictReader(stream))
        with combined.open("w", encoding="utf-8", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=["name", "smiles", "label"])
            writer.writeheader()
            for item in records:
                writer.writerow({k: item[k] for k in ("name", "smiles", "label")})
        out = outroot / name
        cmd = [sys.executable, str(CLI), "--pdb", str(config["pdb"]), "--ligands", str(combined), "--out", str(out),
               "--ligand-resname", config["ligand"], "--exhaustiveness", str(args.exhaustiveness), "--seed", str(args.seed), "--qc"]
        if args.reliability:
            cmd += ["--reliability", "--seeds", str(args.seeds), "--topk", str(args.topk)]
        print("Running:", " ".join(cmd), flush=True)
        completed = subprocess.run(cmd, cwd=ROOT, text=True, check=False)
        metrics_file = out / "metrics.json"
        if not metrics_file.exists():
            runs.append({"target": name, "status": "failed", "return_code": completed.returncode})
            continue
        measured = json.loads(metrics_file.read_text(encoding="utf-8"))
        measured.update({"target": name, "status": "completed" if completed.returncode == 0 else "partial"})
        runs.append(measured)
    (outroot / "benchmark.json").write_text(json.dumps(runs, indent=2), encoding="utf-8")
    rows = ["# DockLab benchmark results", "", f"Generated by `benchmark/run_benchmark.py` with seed {args.seed} and exhaustiveness {args.exhaustiveness}.", "", "| Target | Input ligands | Docked | Failed | Redock RMSD (Å) | Key residue recovery | ROC-AUC | EF5 | Runtime (s) |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for item in runs:
        if item.get("status") == "failed":
            rows.append(f"| {item['target']} | — | — | — | — | — | — | — | — |")
            continue
        redock = item.get("redocking") or {}
        screening = item.get("screening") or {}
        def fmt(value): return "—" if value is None else f"{value:.3f}" if isinstance(value, float) else str(value)
        rows.append(f"| {item['target']} | {item.get('ligand_count','—')} | {item.get('docked_count','—')} | {item.get('failed_count','—')} | {fmt(redock.get('rmsd'))} | {fmt(redock.get('recovery_pct'))} | {fmt(screening.get('roc_auc'))} | {fmt(screening.get('ef5'))} | {fmt(item.get('runtime_seconds'))} |")
    rows += ["", "The values above are written only from measured CLI output. A dash means that the corresponding metric was not available. Vina scores and repeatability describe computation, not biological activity.", "", "Per-target raw results and metrics are in `benchmark/results/<target>/`; `benchmark.json` stores this run's machine-readable summary.", ""]
    (ROOT / "benchmark" / "RESULTS.md").write_text("\n".join(rows), encoding="utf-8")
    return 0 if all(item.get("status") == "completed" for item in runs) else 1


if __name__ == "__main__":
    raise SystemExit(main())
